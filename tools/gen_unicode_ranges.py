#!/usr/bin/env python3
r"""Generates src/unicode_ranges.h: what the Qwen2 tokenizer needs from the
Unicode database, from Python's unicodedata:

- the \p{L} and \p{N} code point ranges of the pre-tokenizer regex,
- the canonical decompositions, combining classes and primary compositions
  of NFC, the normalizer that runs before it.

    python tools/gen_unicode_ranges.py > src/unicode_ranges.h
"""
import sys
import unicodedata

SBASE, SCOUNT = 0xAC00, 11172  # Hangul syllables: decomposed algorithmically, not tabled


def ranges(prefix):
    out, start = [], None
    for cp in range(0x110000):
        hit = unicodedata.category(chr(cp)).startswith(prefix)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def ccc_ranges():
    out = []
    for cp in range(0x110000):
        c = unicodedata.combining(chr(cp))
        if not c:
            continue
        if out and out[-1][1] == cp - 1 and out[-1][2] == c:
            out[-1][1] = cp
        else:
            out.append([cp, cp, c])
    return out


def decompositions():
    """Full (recursive) canonical decompositions, Hangul excluded."""
    out = []
    for cp in range(0x110000):
        if SBASE <= cp < SBASE + SCOUNT:
            continue
        d = unicodedata.normalize("NFD", chr(cp))
        if d != chr(cp):
            out.append((cp, [ord(c) for c in d]))
    return out


def compositions():
    """Primary composites: pairs NFC composes back into one code point."""
    out = []
    for cp in range(0x110000):
        if SBASE <= cp < SBASE + SCOUNT:
            continue
        raw = unicodedata.decomposition(chr(cp))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(x, 16) for x in raw.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            out.append((parts[0], parts[1], cp))
    return sorted(out)


def table(ctype, name, rows):
    return f"static const {ctype} {name}[] = {{\n" + "\n".join(f"    {{ {r} }}," for r in rows) + "\n};\n"


decomp = decompositions()
flat, entries = [], []
for cp, seq in decomp:
    entries.append(f"0x{cp:04X}, {len(flat)}, {len(seq)}")
    flat += seq

sys.stdout.write(
    "#pragma once\n"
    f"// GENERATED by tools/gen_unicode_ranges.py (Unicode {unicodedata.unidata_version}), do not edit.\n"
    "// Every table is sorted by its first field, for binary search.\n\n"
    "struct UnicodeRange {\n    int lo, hi;\n};\n\n"
    "struct UnicodeCombiningClass {\n    int lo, hi, ccc;\n};\n\n"
    "struct UnicodeDecomposition {\n    int cp, offset, length;  // into UNICODE_DECOMPOSITION_CODES\n};\n\n"
    "struct UnicodeComposition {\n    int first, second, composite;\n};\n\n"
    + table("UnicodeRange", "UNICODE_LETTER_RANGES", [f"0x{a:04X}, 0x{b:04X}" for a, b in ranges("L")]) + "\n"
    + table("UnicodeRange", "UNICODE_NUMBER_RANGES", [f"0x{a:04X}, 0x{b:04X}" for a, b in ranges("N")]) + "\n"
    + table("UnicodeCombiningClass", "UNICODE_COMBINING_CLASSES", [f"0x{a:04X}, 0x{b:04X}, {c}" for a, b, c in ccc_ranges()]) + "\n"
    + table("UnicodeDecomposition", "UNICODE_DECOMPOSITIONS", entries) + "\n"
    + "static const int UNICODE_DECOMPOSITION_CODES[] = {\n"
    + "\n".join("    " + ", ".join(f"0x{c:04X}" for c in flat[i:i + 12]) + "," for i in range(0, len(flat), 12))
    + "\n};\n\n"
    + table("UnicodeComposition", "UNICODE_COMPOSITIONS", [f"0x{a:04X}, 0x{b:04X}, 0x{c:04X}" for a, b, c in compositions()])
)
